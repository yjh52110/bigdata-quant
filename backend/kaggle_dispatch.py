PUSH_TIMEOUT_S = 180

# Kaggle's own validation: "Kernel slug must be at least five characters".
MIN_SLUG_LEN = 5


class DispatchError(RuntimeError):
    pass


def _load_jobs() -> List[Dict[str, Any]]:
    try:
        with open(JOBS_FILE) as f:
            data = json.load(f)
        return data if isinstance(data, list) else []
    except (OSError, json.JSONDecodeError):
        return []


# Params that carry a live credential. They have to reach the kernel, but they
# must never reach the job log: GitHub's secret scanner caught exactly this,
# blocking a push because a persisted drive_access_token sat in kaggle_jobs.json.
SECRET_PARAM_KEYS = ("drive_access_token", "access_token", "token", "secret",
                     "client_secret", "refresh_token", "password", "api_key")


def _redact(params: Dict[str, Any]) -> Dict[str, Any]:
    """Copy of the params with credential values replaced by a marker."""
    out = {}
    for k, v in (params or {}).items():
        if any(s in k.lower() for s in SECRET_PARAM_KEYS):
            out[k] = f"<redacted {len(str(v))} chars>"
        else:
            out[k] = v
    return out


def _save_jobs(jobs: List[Dict[str, Any]]) -> None:
    os.makedirs(os.path.dirname(JOBS_FILE), exist_ok=True)
    tmp = JOBS_FILE + ".part"
    with open(tmp, "w") as f:
        json.dump(jobs[-200:], f, indent=2)
    # Atomic so a crash mid-write can't leave a truncated job list behind.
    os.replace(tmp, JOBS_FILE)


def build_metadata(username: str, slug: str, title: str, code_file: str,
                   enable_gpu: bool = False, enable_tpu: bool = False,
                   dataset_sources: Optional[List[str]] = None) -> Dict[str, Any]:
    """kernel-metadata.json contents.

    enable_internet defaults to False on Kaggle, which would silently break
    every job this project dispatches (they all fetch from S3 / Binance /
    Drive), so it is forced on here rather than left to the caller.
    """
    if len(slug) < MIN_SLUG_LEN:
        raise DispatchError(f"slug must be at least {MIN_SLUG_LEN} characters: {slug!r}")
    if "/" in slug:
        raise DispatchError(f"slug must not contain a slash: {slug!r}")
    return {
        "id": f"{username}/{slug}",
        "title": title,
        "code_file": code_file,
        "language": "python",
        "kernel_type": "script",
        # Private: these scripts carry job parameters and read secrets.
        "is_private": True,
        "enable_gpu": enable_gpu,
        "enable_tpu": enable_tpu,
        "enable_internet": True,
        "dataset_sources": dataset_sources or [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }


