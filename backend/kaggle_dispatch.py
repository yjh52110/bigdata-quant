DRIVE_REST_PATH = os.path.join(os.path.dirname(__file__), "drive_rest.py")


def render_script(params: Dict[str, Any]) -> str:
    """Builds the self-contained kernel script.

    drive_rest.py is embedded rather than shipped alongside: `kernels push`
    uploads the folder, but Kaggle only treats code_file as the kernel source,
    so a sibling module is not importable in the runtime -- measured, the job
    failed with "No module named 'drive_rest'". The repo still holds exactly one
    copy; it is materialised into the script at dispatch time.
    """
    with open(DRIVE_REST_PATH) as f:
        module_src = f.read()
    body = _INGEST_SCRIPT.replace(
        "__PARAMS__", json.dumps(params).replace('"""', '\\"\\"\\"'))
    return (
        "# --- begin embedded backend/drive_rest.py (do not edit here) ---\n"
        "import sys as _sys, types as _types\n"
        "_m = _types.ModuleType('drive_rest')\n"
        "_m.__dict__['__name__'] = 'drive_rest'\n"
        f"exec(compile({module_src!r}, 'drive_rest.py', 'exec'), _m.__dict__)\n"
        "_sys.modules['drive_rest'] = _m\n"
        "# --- end embedded module ---\n\n"
        + body
    )


# Prefer the URL Kaggle prints, because the slug it actually used may differ
# from the one we asked for (see _slugify below).
_URL_REF_RE = re.compile(r"kaggle\.com/(?:code|kernels/scripts)/([\w-]+/[\w-]+)", re.I)
_REF_RE = re.compile(r"(?:ref|url)\D*([\w-]+/[\w-]+)", re.I)
_VERSION_RE = re.compile(r"version\s*(\d+)", re.I)


def _slugify(title: str) -> str:
    """Kaggle's slug derivation, needed because it wins over metadata `id`.

    Observed: pushing id=yjh980/cq-drivecheck with title="ChainQuant drive
    connectivity check" created yjh980/chainquant-drive-connectivity-check, and
    every later `kernels status`/`output` call on the requested id failed with
    "Permission 'kernels.get' was denied". The push does warn -- "Your kernel
    title does not resolve to the specified id" -- so the two must be kept
    consistent rather than set independently.
    """
    out = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return re.sub(r"-{2,}", "-", out)


def dispatch(username: str, slug: str, params: Dict[str, Any], *,
             title: Optional[str] = None, timeout: Optional[int] = None,
             enable_gpu: bool = False, enable_tpu: bool = False) -> Dict[str, Any]:
    """Pushes one job and records it. Returns immediately -- Kaggle queues it."""
    st = cli_status()
    if not st["installed"]:
        raise DispatchError("kaggle CLI not installed")
    if not st["authenticated"]:
        raise DispatchError(st["auth_hint"] or "kaggle CLI not authenticated")

    folder = tempfile.mkdtemp(prefix="kaggle-job-")
    try:
        code_file = "job.py"
        with open(os.path.join(folder, code_file), "w") as f:
            f.write(render_script(params))
        # `kernels push` uploads the whole folder, so the Drive client rides
        # along as a real module rather than being string-inlined. One source of
        # truth shared with the Colab worker.
        shutil.copy(os.path.join(os.path.dirname(__file__), "drive_rest.py"),
                    os.path.join(folder, "drive_rest.py"))
        # If the caller's title would slugify to something else, Kaggle would
        # silently file the kernel under that instead, orphaning our handle.
        effective_title = title or slug
        if _slugify(effective_title) != slug:
            logging.info(
                f"title {effective_title!r} slugifies to {_slugify(effective_title)!r}, "
                f"not {slug!r}; using the slug as the title so the ref stays valid")
            effective_title = slug
        meta = build_metadata(username, slug, effective_title, code_file,
                              enable_gpu=enable_gpu, enable_tpu=enable_tpu)
        with open(os.path.join(folder, "kernel-metadata.json"), "w") as f:
            json.dump(meta, f, indent=2)

        args = ["kernels", "push", "-p", folder]
        if timeout:
            # Seconds only. `kernels push -t` is argparse type=int: passing a
            # duration string such as "15m" is rejected outright. (Other
            # commands do accept "1h"/"30s" forms -- this one does not.)
            args += ["-t", str(int(timeout))]
        r = _run(args, timeout=PUSH_TIMEOUT_S)
        text = (r["out"] + r["err"]).strip()
        if not r["ok"]:
            raise DispatchError(text[:400] or "kernels push failed")

        url_m = _URL_REF_RE.search(text)
        ref_m = _REF_RE.search(text)
        ver_m = _VERSION_RE.search(text)
        job = {
            # URL first: it is what Kaggle actually created.
            "ref": url_m.group(1) if url_m else (ref_m.group(1) if ref_m else f"{username}/{slug}"),
            "version": int(ver_m.group(1)) if ver_m else None,
            "slug": slug,
            # Redacted: this record is written to disk and read by the dashboard.
            "params": _redact(params),
            "pushed_at": time.time(),
            "status": "QUEUED",
            "push_output": text[:400],
        }
        if "does not resolve to the specified id" in text:
            # Should be unreachable now, but surface it rather than hide it.
            job["warning"] = "kaggle reported a title/id slug mismatch"
        jobs = _load_jobs()
        jobs.append(job)
        _save_jobs(jobs)
        logging.info(f"dispatched kaggle kernel {job['ref']}")
        return job
    finally:
        shutil.rmtree(folder, ignore_errors=True)


_STATUS_RE = re.compile(r'"?(QUEUED|RUNNING|COMPLETE|ERROR|CANCEL_REQUESTED|'
                        r'CANCEL_ACKNOWLEDGED|NEW_SCRIPT)"?', re.I)


def status(ref: str) -> Dict[str, Any]:
    r = _run(["kernels", "status", ref], timeout=60)
    text = (r["out"] + r["err"]).strip()
    m = _STATUS_RE.search(text)
    state = m.group(1).upper() if m else None
    return {"ref": ref, "state": state, "done": state in DONE_STATES,
            "raw": text[:400], "ok": r["ok"]}


def refresh_jobs() -> List[Dict[str, Any]]:
    """Polls non-terminal jobs and persists whatever changed."""
    jobs = _load_jobs()
    changed = False
    for j in jobs:
        if j.get("status") in DONE_STATES:
            continue
        s = status(j["ref"])
        if s["state"] and s["state"] != j.get("status"):
            j["status"] = s["state"]
            j["checked_at"] = time.time()
            changed = True
    if changed:
        _save_jobs(jobs)
    return jobs


def fetch_output(ref: str, dest_dir: str) -> Dict[str, Any]:
    """Downloads a finished kernel's output and reads back result.json."""
    os.makedirs(dest_dir, exist_ok=True)
    r = _run(["kernels", "output", ref, "-p", dest_dir, "-o"], timeout=900)
    text = (r["out"] + r["err"]).strip()
    out: Dict[str, Any] = {"ref": ref, "ok": r["ok"], "dest": dest_dir, "raw": text[:400]}
    rj = os.path.join(dest_dir, "result.json")
    if os.path.exists(rj):
        try:
            with open(rj) as f:
                out["result"] = json.load(f)
        except json.JSONDecodeError as e:
            out["result_error"] = str(e)
    files = [os.path.join(p, f) for p, _, fs in os.walk(dest_dir) for f in fs]
    out["files"] = len(files)
    out["bytes"] = sum(os.path.getsize(f) for f in files)
    return out


def logs(ref: str) -> Dict[str, Any]:
    r = _run(["kernels", "logs", ref], timeout=120)
    return {"ref": ref, "ok": r["ok"], "logs": (r["out"] + r["err"])[-4000:]}


def list_jobs() -> List[Dict[str, Any]]:
    return list(reversed(_load_jobs()))
